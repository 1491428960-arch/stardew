"""清掉中文台词里漏进来的拉丁／假名碎片。

**成因已查实（2026-09-24）：模型幻觉，不是素材传染。**
证据两条：

1. 索菲亚的 **310 条**索引素材零污染（0 个 `_XX` 标记、0 个拉丁字母、
   0 个 ID 前缀）；全库仅 7 条含标记，都在 Lance / Mermaid / Wizard 身上，
   进不了她的 prompt。
2. 逐卡扫描 prompt 只找到 **39 处**拉丁串，全是指令**引用自己的字段名**
   （「`npcIdentity.voiceStyle` 是当前…」「`voiceAnchors` 是正向原…」），
   属于说明性文字，不是可照抄的内容。

prompt 侧那句「请用简洁、自然的中文回复」（`providers.py`）与
`safety_rules` 的「只生成当前 NPC 的中文游戏对白」**都已经存在，但拦不住**，
所以防线只能放在出口。

**为什么是清理而不是加约束**：项目铁律是「反机械感靠减约束、给示例，
不靠加规则」。这里不改 prompt、不加指令，只把已经漏出来的碎片擦掉 ——
对模型的表达空间没有任何影响。

**保守原则**（实测校准）：在 8765 轮历史输出上只改动 **0.2%**。
- 整段不是中文时**一个字都不碰**（纯英文回复是另一类问题，在这里动手会删光）；
- 什么都没删到就原样返回，**不做任何空白规范化** ——
  早期版本顺手压掉了行尾双空格，那是 markdown 硬换行，
  在 216 轮「改动」里占了绝大多数，纯误伤。

**2026-10-02 的唯一例外：段落换行会被收掉**（见 `_NEWLINE`）。
它不违反上面第二条 —— 那条说的是**空白规范化**（把 `  ` 压成 ` `），
而换行是**要被删掉的对象本身**：
- 段落**内部**的双空格照旧保留（markdown 硬换行，有语义）；
- 只有**紧挨着换行**的空白随换行一起收掉 —— 它们已经没有可断的行了。
"""

from __future__ import annotations

import re

_CJK = re.compile(r"[\u4e00-\u9fff]")

#: 中文与中文标点 —— 碎片的左右邻必须是其中之一，这样「夹在中文里的英文」
#: 才会被认出来，而整句英文、URL、跟在英文后面的词都不受影响。
_CJK_OR_PUNCT = r"[\u4e00-\u9fff，。！？、；：…—「」『』（）【】〈〉《》]"

#: `{{<purple>}}` / `{{</purple>}}` 这类标记语法。
_MARKUP = re.compile(r"\{\{[^{}]*\}\}")

#: `_CELLPHONE_MAINMENU_` / `毯子_GE` 这类 i18n 标记。
_I18N = re.compile(r"(?<![A-Za-z0-9])_+[A-Za-z0-9]+(?:_[A-Za-z0-9]+)*_{0,}(?![A-Za-z0-9])")

#: 夹在中文里的拉丁词（含被截断的残片，如 `utting`、`Rgb`）。
#: 用**捕获组**而不是 lookbehind：组 1 是左邻（要保留），组 2 是拉丁部分
#: （用来查白名单）—— 只按 `group(0)` 判白名单会连左邻的中文一起算进去。
_LATIN = re.compile(
    rf"({_CJK_OR_PUNCT})[ \t]*([A-Za-z][A-Za-z0-9'’\-]*"
    rf"(?:\s+[A-Za-z][A-Za-z0-9'’\-]*)*)[ \t]*(?={_CJK_OR_PUNCT})"
)

#: 夹在中文里的假名（实测出现过 `ティーほかもない`）。
_KANA = re.compile(rf"({_CJK_OR_PUNCT})[ \t]*[\u3040-\u309f\u30a0-\u30ffー]{{2,}}[ \t]*(?={_CJK_OR_PUNCT})")

#: **行尾／段尾**的拉丁碎片（2026-09-26 补）。
#:
#: 实测形态（`victor-ab-before2-20260926-120422` 第 2 轮输出末尾）：
#:     ...卸载了。\n\n你玩什么？ounced
#: 左邻是中文标点、**右邻是句尾** —— 而 `_LATIN` 的前瞻要求右邻也是中文，
#: 于是句尾的碎片一路漏出出口。这是 `_LATIN` 的**边界**，不是新一类问题。
#:
#: 尾随空白写在**前瞻里**（不进 `group(0)`）：删掉碎片不该顺手吃掉行尾双空格，
#: 那是 markdown 硬换行，有语义（见文件头「保守原则」第二条）。
_LATIN_AT_TAIL = re.compile(
    rf"({_CJK_OR_PUNCT})[ \t]*([A-Za-z][A-Za-z0-9'’\-]*"
    rf"(?:\s+[A-Za-z][A-Za-z0-9'’\-]*)*)(?=[ \t]*$)",
    re.MULTILINE,
)

#: **必须留下的拉丁串**。
#:
#: ⚠ **这份名单与 `guard.ResponseGuard._allowed_english` 是故意不同的，不要合并。**
#: 2026-09-27 我一度以为两处只是漏了同步，就把它们接成同源 —— 结果
#: `test_api.py::test_fake_dialogue_returns_structured_response` 立刻变红，
#: 而**它是对的**。两处判的压根不是一回事：
#:
#: | | 判什么 | 宽窄 |
#: |---|---|---|
#: | `guard._allowed_english` | 这个词算不算「模型输出外语」 | **宽** —— 放行 42 个角色名，避免无谓重试 |
#: | 这里 | 这个词**能不能给玩家看** | **窄** —— 中文台词里露英文名就是错的 |
#:
#: 两者是**配合**工作的：`Rasmodia` 这类 mod 英文标识在 guard 那边不触发重试
#: （重试也没用，它本来就是那个词），但**到这里必须被擦掉** ——
#: 玩家在游戏里看到的是中文显示名。原名单 42 项**全是角色名**，
#: 说明这个分工是当初就想清楚的。
#:
#: 目前只有一条，但它很关键：
#: `FakeProvider` 的降级提示写作「本地演示·非真实 AI」，
#: 早期版本把 `AI` 当碎片删掉，于是提示变成「本地演示·非真实」——
#: **一句在骗人的提示，比一句夹了英文的提示糟得多。**
#: 实测教训：清洗规则的第一个问题是「它会不会删掉不该删的」，
#: 而不是「它能不能删干净」。
#:
#: 2026-09-28 扩充：**品牌／作品名与角色名是两类**。角色名露英文是错的
#: （`Shane` 该删），但原版中文**自己就保留**了一批拉丁词 —— 扫 32126 条原版中文
#: 文本（`scan_keep_latin.py`）共得 11 个，`Joja` 一家 **401 次**
#: （「鹈鹕镇 Joja 超市」，见 `personas.py:114` 引的 Morris 初见台词）。
#: 把它删掉的后果**比留着英文更糟，因为读起来毫无异常**：
#:
#:     我在 Joja 上班。  ->  我在上班。        # 语义被改：在 Joja 工作 ≠ 在上班
#:     我今天去了 Joja。  ->  我今天去了。      # 句子直接残缺
#:
#: 这是**静默损坏** —— 输出通顺、没有告警，谁都不会发现。所以这类词一律放行。
#: 判据是「**原版中文里出现过**」（与 `addressing.player` 的「按真原话」同一口径），
#: 不是「看起来像专有名词」：名单由语料决定，不靠人猜。
#: 已排除 `oja`（`Joja` 被控制符切断后的碎片，放行等于让碎片活下来）
#: 与 `D`（单字符，误伤面太大）。
#:
#: ⚠ **一律小写，比对时 `.casefold()`** —— 与 `guard` 保持一致
#: （`guard.format_issue` 用的是 `match.group(0).casefold() not in cls._allowed_english`）。
#: 2026-09-28 实测出的反例：精确匹配时 `我在 joja 上班。` 与 `我在 JOJA 上班。`
#: 照样被删成「我在上班。」，`JojaMart` 也漏在名单外。
#: 而「**本地演示·非真实 ai**」→「本地演示·非真实」正是上面那条 `AI` 教训的
#: **小写变体** —— 说明当初那次修复只补了写法、没改比对方式，**并不完整**。
_KEEP_LATIN = frozenset(
    {
        "ai",  # 降级提示「本地演示·非真实 AI」
        "joja",
        "jojacd",
        "jojafamily",
        "jojamart",
        "jojo",  # 鹈鹕镇的超市品牌及其变体
        "boss",
        "css",
        "i-63z",
        "lv2103",
        "metube",  # 原版彩蛋／作品名
    }
)

#: 半角连续句点（`...`）—— 中文里的省略号该写 `……`（2026-09-27 补）。
#:
#: 实测形态（`docs/active-work.md` 条目 60 的真实生成验证，`fall-9-sam`）：
#:     呃，就那种...滑板鞋，高帮的，侧边有条纹。
#: 它同时躲过了两道防线：`_LATIN` 要求以 `[A-Za-z]` 开头；`format_issue`
#: 的四类噪声（markdown / stage_direction / english / leading_punctuation）
#: 也都不认它 —— 于是它一路漏到玩家眼前。
#:
#: ⚠ **只收两个及以上**，单个 `.` 一个都不碰：`3.14`、`Mr.`、`example.com`
#: 都要留。半角 `,` `!` `?` 同理不收 —— 收了会把 `1,000` 变成 `1，000`，
#: 那是误伤。这与文件头的「先问会不会删掉不该删的」是同一条纪律。
#:
#: 邻接要求与 `_LATIN` 一致（左邻须是中文或中文标点），所以整段英文、
#: 代码、URL 一概不受影响。用 lookbehind 而不是捕获组（宽度恒为 1）。
_DOTS = re.compile(rf"(?<={_CJK_OR_PUNCT})\.{{2,}}(?={_CJK_OR_PUNCT})")

#: 同上，但允许**句尾／行尾**。与 `_LATIN_AT_TAIL` 是同一个边界问题：
#: `_DOTS` 的前瞻要求右邻也是中文，句尾那一份就漏了。
#: 尾随空白写在前瞻里（不进 `group(0)`），免得顺手吃掉行尾双空格。
_DOTS_AT_TAIL = re.compile(rf"(?<={_CJK_OR_PUNCT})\.{{2,}}(?=[ \t]*$)", re.MULTILINE)

#: 删掉碎片后可能留下「空格 + 中文标点」，或「中文标点 + 空格」。
#: ⚠ 两处都用 `[ \t]` 而非 `\s`，并且 `(?=\S)` 保证后面还有内容 ——
#: 行尾的「。  \n」是 markdown 硬换行，不能被吃掉。
_SPACE_BEFORE_PUNCT = re.compile(r"[ \t]+([，。！？、；：])")
_SPACE_AFTER_PUNCT = re.compile(r"([，。！？、；：])[ \t]+(?=\S)")


#: **行首**的拉丁碎片（2026-09-28 补，与 `_LATIN_AT_TAIL` 对称）。
#:
#: `_LATIN` 要求左邻是中文或中文标点 —— 行首没有左邻，于是整条漏出出口。
#: 实测形态（`active-work.md` 记的「艾芙琳说 Alex」）：
#:     Shane 说他明天要去镇上。
#: 左邻是行首、右邻是中文，`_LATIN` 与 `_LATIN_AT_TAIL` 都不认它。
#: 这与 09-26 补的行尾是**同一个边界问题**，只是另一侧。
#:
#: ⚠ 形态收得比 `_LATIN` **更窄**，两处都踩过坑（详见报告）：
#:   · 必须**后跟空格再跟汉字**（`[ \t]+(?=[\u4e00-\u9fff])`）——
#:     若只要求「后跟中文标点」，兜底文案 `Rasmodia：我们改天再聊。` 的说话人
#:     前缀会被删成「：我们改天再聊。」，`test_api.py:970` 立刻变红；
#:   · 因此英文后紧跟标点的形态（`Alex，你来了。`）**不碰** ——
#:     删了会留下孤立逗号「，你来了。」，比留着更怪。
#: 清洗规则的第一个问题始终是「它会不会删掉不该删的」。
_LATIN_AT_HEAD = re.compile(
    rf"^[ \t]*([A-Za-z][A-Za-z0-9'\u2019\-]*(?:\s+[A-Za-z][A-Za-z0-9'\u2019\-]*)*)"
    rf"[ \t]+(?=[\u4e00-\u9fff])",
    re.MULTILINE,
)


def _drop_latin(match: re.Match[str]) -> str:
    """删掉匹配到的拉丁碎片，但放行 `_KEEP_LATIN` 里的。"""

    if match.group(2).strip().casefold() in _KEEP_LATIN:
        return match.group(0)
    return match.group(1)


def _drop_latin_at_head(match: re.Match[str]) -> str:
    """行首碎片没有左邻可保留，直接删；白名单照旧放行。"""

    if match.group(1).strip().casefold() in _KEEP_LATIN:
        return match.group(0)
    return ""


#: **段落换行**（2026-10-02 用户要求）。
#:
#: 用户在游戏里看到回复中间有个突兀的空行，说「看着奇怪，别分行，两段接成一句」。
#: 形态高度一致 —— 模型习惯先甩一句短的、空行、再展开：
#:     嘿！\n\n我刚从矿洞那边回来——那边第三层有块石头，敲开里面居然是水晶。
#: 实测采样的 206 处含换行回复里，**205 处是 `\n\n`**，只有 1 处是单个换行。
#:
#: 游戏对话框是个单行气泡，空行既不是排版也不是停顿；中文本来就靠标点断句，
#: 所以**直接拼接**、不补任何字符。换行两侧的空白一并收掉，
#: 免得留下「。  给你」这种双空格。
#:
#: ⚠ 这个改动**扩大了 `_LATIN_AT_TAIL` 的射程**，但只覆盖一种形态：
#: 「中文。\n\nEnglish line」里的行尾英文，以前左邻是换行、不在 `_CJK_OR_PUNCT`
#: 里，因而不匹配、漏给玩家；换行收掉后左邻变成中文标点。
#: **行尾带标点的（`farming.`）仍然不匹配** —— 那条正则的前瞻是 `(?=[ \t]*$)`，
#: 句尾的 `.` 会让它回溯失败。这个边界与本次改动无关，是它本来就有的。
#: 我先猜成「整行英文都会被删」，被
#: `test_reply_scrub.py::test_trailing_english_line_after_a_paragraph_break`
#: 纠正回来，那边如实钉住了两种形态的实际结果。
#:
#: ⚠ 位置在中文判定**之后**：纯英文回复仍然整段不碰（那是另一类问题，
#: 见 `test_pure_english_reply_is_left_alone`），在这里动手只会把整句删光。
_NEWLINE = re.compile(r"[ \t]*(?:\r?\n)+[ \t]*")


def scrub_reply(text: str) -> str:
    """返回清理后的台词。没有可清的就**原样返回**。"""

    if not text or len(_CJK.findall(text)) < 2:
        # 整段不是中文 —— 不做处理。在这里动手只会把整句删光。
        return text

    # 段落换行先收掉：它是**版式**问题，而且删掉之后原本挨着换行的行尾碎片
    # 会落回清洗射程（见 `_NEWLINE` 注释）。
    out = _NEWLINE.sub("", text)
    out = _MARKUP.sub("", out)
    out = _I18N.sub("", out)
    # 相邻碎片删掉后可能又接出新的一对，迭代到稳定（上限 3 次即可收敛）。
    for _ in range(3):
        new = _KANA.sub(r"\1", out)
        new = _LATIN.sub(_drop_latin, new)
        new = _LATIN_AT_HEAD.sub(_drop_latin_at_head, new)
        new = _LATIN_AT_TAIL.sub(_drop_latin, new)
        new = _DOTS.sub("……", new)
        new = _DOTS_AT_TAIL.sub("……", new)
        if new == out:
            break
        out = new

    if out == text:
        return text

    # ⚠ 只清理**行内**：不动行尾空白（markdown 硬换行有语义）。
    out = re.sub(r"[ \t]{2,}", " ", out)
    out = _SPACE_BEFORE_PUNCT.sub(r"\1", out)
    out = _SPACE_AFTER_PUNCT.sub(r"\1", out)
    return out
