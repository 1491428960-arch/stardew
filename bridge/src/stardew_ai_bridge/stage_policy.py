def _facet_hits(text: object) -> set[str]:
    """一句话命中了哪些生活面。命中即算，不做互斥裁决——宽松判定下宁可多禁一次。"""

    if not isinstance(text, str) or not text.strip():
        return set()
    return {name for name, pattern in _LIFE_FACET_PATTERNS if re.search(pattern, text)}


def _facet_of_topic(topic: object) -> str | None:
    """把一条素材（preferredTopics 条目）映射到**一个**生活面。

    2026-09-21：这里原先写的是 `next(iter(_facet_hits(...)))` —— 从一个 `set`
    里取"第一个"元素。字符串哈希在 CPython 里按进程随机化，同一个条目在不同进程
    可能映射到**不同的面**，于是 `banned` 的挑选、`suggestedTopic` 的筛选、
    以及基于它们的测试断言全都不可复现。改回**按 `_LIFE_FACET_PATTERNS` 的声明
    顺序**取第一个命中：既确定，也把"哪一面优先"变成一处可读、可改的显式配置。

    一条素材同时命中多面是常态（「她刚到镇上那阵子住的旧房子」同时含"镇上"与
    "那阵子"），所以"取第一个"必须有确定规则，不能听天由命。
    """

    if not isinstance(topic, str) or not topic.strip():
        return None
    for name, pattern in _LIFE_FACET_PATTERNS:
        if re.search(pattern, topic):
            return name
    return None


def narrow_topic_pool(
    preferred_topics: object = None,
    banned_facet: object = None,
) -> list[str]:
    """落点池**排除被禁生活面**后的那一份（2026-09-21 二次）。

    槽位说「不要再出现工作面」而 `roleGuidance` 的 `{topicPool}` 还列着「酒窖里
    这一批新酿」——两层并排就是"一紧一松、取最松"，正是本文件记过三次的形状。
    收窄之后「槽位禁什么」与「guidance 还列什么」不可能再打架。

    降级：过滤后为空（该角色素材**全部**落在被禁面）时返回空列表，调用方据此退回
    `_DEFAULT_TOPIC_POOL_PHRASE` 的不点名说法。**不能**退回原始列表——那等于把
    被禁面又写回 prompt；更不能留下空占位符（"落点在之间轮换"是读不通的指令）。
    """

    topics = [
        item.strip()
        for item in (preferred_topics if isinstance(preferred_topics, (list, tuple)) else ())
        if isinstance(item, str) and item.strip()
    ]
    banned = str(banned_facet).strip() if banned_facet is not None else ""
    if not banned:
        return topics
    # 2026-09-23：判据从「**主面**不等于被禁面」收紧为「**命中**即摘」。
    #
    # 起因：`_facet_of_topic` 取**声明顺序里第一个命中的面**，而全库 8717 条里有
    # **713 条（8%）同时命中 ≥2 个面** —— 这些条目的主面完全由**声明顺序**决定，
    # 与内容轻重无关。于是"禁了工作面、素材却因为主面是别的面而留下"这种漏网真实存在
    # （Harvey「天气、咖啡、收音机和小镇见闻」禁天气或禁镇上**都漏**）。
    #
    # 代价实测为**零**：396 个（角色 × 面）组合里，"命中即摘"后池子被**摘空的增量是 0**，
    # 只有 24 个组合各少 1~2 条、最少仍剩 3 条（报告 §9.3）。所以下面的降级分支
    # （返回空列表）比改之前更不容易触发，不是更容易。
    return [topic for topic in topics if banned not in _facet_hits(topic)]


def _player_reply_text(value: object) -> str:
    """玩家一条回复的可用文本（首尾空白去掉，其余原样保留）。"""

    return value.strip() if isinstance(value, str) and value.strip() else ""


def _reply_digest(value: object) -> str:
    """只留汉字与字母数字：长度判定与"整句由空转词拼成"的判定都基于它。

    标点与空白不参与 —— 「嗯……」「嗯，」和「嗯」是同一句话。
    """

    return re.sub(r"[^\u4e00-\u9fffA-Za-z0-9]", "", value).casefold()


def _is_player_refusal(text: str) -> bool:
    """玩家在划边界（不想继续刚才那件事）。**不是**敷衍，见常量区那三条防误判。"""

    return any(marker in text for marker in _PLAYER_REFUSAL_MARKERS)


def _is_player_topic_request(text: str) -> bool:
    """玩家明确点名要换话题。"""

    return any(marker in text for marker in _PLAYER_TOPIC_REQUEST_MARKERS)


def _is_short_filler_reply(text: str) -> bool:
    """很短**且**整句由空转词拼成 —— 两条都满足才算"玩家没接住"。

    "很短"用净字数（≦ ``_SHORT_REPLY_MAX_CHARS``）；"敷衍"用完整切分，
    所以「嗯，你说得对」不算（它带着一个实义判断）。
    """

    digest = _reply_digest(text)
    if not digest or len(digest) > _SHORT_REPLY_MAX_CHARS:
        return False
    return bool(_PLAYER_FILLER_FULL_PATTERN.match(digest))


def _bridge_anchor(reply: object) -> str:
    """上一轮回复里可被引用的那半句，作为关联过渡的引用起点。

    取法是"**完整的短句，凑不满就停**"：先按句末标点取首句，超长再按逗号切分句、
    累积到 ``_BRIDGE_ANCHOR_LIMIT`` 为止。硬截会产生「是啊，葡萄园的收成很好，
    我又酿了」这种**腰斩**的引用 —— 让模型"从它拉一根线"，而它自己都是一句断话。
    """

    text = _player_reply_text(reply)
    if not text:
        return ""
    first = re.split(r"[。！？!?；;\n]", text)[0].strip("，,、:： ")
    if not first:
        first = text
    if len(first) <= _BRIDGE_ANCHOR_LIMIT:
        return first
    anchor = ""
    for part in re.split(r"[，,、]", first):
        part = part.strip()
        if not part:
            continue
        if not anchor:
            if len(part) > _BRIDGE_ANCHOR_LIMIT:
                # 第一个分句就超长：没有更好的选择，硬截。
                anchor = part[:_BRIDGE_ANCHOR_LIMIT]
                break
            anchor = part
            continue
        if len(anchor) + len(part) + 1 > _BRIDGE_ANCHOR_LIMIT:
            break
        anchor = f"{anchor}，{part}"
    return anchor


def _facet_per_turn(
    replies: list[str],
    turn_players: object = (),
) -> list[set[str]]:
    """每一轮命中的生活面：先看她的话，**她一个面都判不出**时借同轮玩家的话。

    这是"指代消解"的落点（2026-09-22）。真实对话里她回应玩家点名的对象时**常常不
    重复名词**：

        · 她「还没画完呢，就差葡萄藤后面那道光」    ← 只有"画"字，靠词表补收才判得出
        · 她「刚封好的那批已经进桶了，颜色比…深」  ← 0 命中，对象在玩家那句「新酿呢？」
        · 她「那批还得再等等」／「那瓶先留着」      ← 量词指代，本身不带任何面语义

    只匹配她的话，"最近几轮都在同一面"在真机上大部分轮次算不出来，整套槽位空转。
    注意**量词本身不该入词表**：「那批货」和「那批新酿」完全不同的面 —— 加"那批／那瓶"
    是把一个无面语义的词当真判据；正确的机理是**把指代还原到同轮那句有实词的话上**。

    **只在她的回复 0 命中时才借**（两个方向都用 `_facet_hits`，不另建词表）：

    * 她说出了落点实词时，结果与改前**逐字相同** —— 这条性质让回归面最小；
    * "有实词就不需要消解"正是指代消解的语义，也是保守方向：漏判的代价只是这一轮
      不换面，误判的代价是她对着玩家正在聊的事硬换台。

    ``turn_players`` 由调用方按 history 的 user → 紧邻 assistant 结构逐项配对
    （与 ``replies`` 等长）。长度不等时按**尾部**对齐：缺的是最早那几轮，而那几轮
    本来也滑出了 `_FACET_LOOKBACK` 窗口。
    """

    aligned: list[str] = []
    if isinstance(turn_players, (list, tuple)) and replies:
        aligned = [_player_reply_text(item) for item in turn_players][-len(replies):]
    offset = len(replies) - len(aligned)

    per_turn: list[set[str]] = []
    for index, reply in enumerate(replies):
        facets = _facet_hits(reply)
        if not facets and index >= offset:
            facets = _facet_hits(aligned[index - offset])
        per_turn.append(facets)
    return per_turn


def _fold_missing_facets(per_turn: list[set[str]]) -> list[set[str]]:
    """把「**判不出面的那一轮**」折算成「继承上一轮的面」（2026-09-22）。

    **为什么要做**：`rotation_topic_slot` 的 `facetRepeat` 判据是"最近 N 轮里同
    一面出现 ≥2 次"。而**判不出面的轮次在计数里等于不存在** —— 于是
    「工作 → 判不出面 → 工作」这种形状，窗口内工作面只算 **1** 次，槽位一次都不触发。

    **这不是理论担忧，是同义词问题**。两批云端实测共 5 轮「判不出面」，逐条判
    **5/5 都是「她说了具体物、但词表没收录」**（酒 / 标签 / 葡萄 / 发酵 / 桶 /
    塞 / 封蜡），没有一条是"她什么实质都没说"。离线形状矩阵
    （`.tmp/topic-probe/facet_shape_matrix.py`）实测：

    | 形状 | 现状 L3/T2 |
    |---|---|
    | 工作 / 无面 交替 | 间歇触发（i=3、5、7），**漏掉一半** |
    | 工作 / 无面 / 吃喝 / 无面 | **8 轮内一次都不触发** |

    折算后前者稳定在 i=2 触发、后者 i=2 触发 —— 与「连续两轮同面」的
    触发时机**对齐**，语义上也对：她那两轮确实都在说同一件事。

    **边界**：
    * 首轮就判不出面时 `last` 为空，保持空 —— 不凭空造面；
    * 只影响 `facetRepeat` 的计数，`bannedFacet` 的另两级证据（`latest` / `default`）
      与 `suggestedTopic` 的筛选逻辑都不变；
    * `_topic_already_spoken` 仍按**原文**判"这条素材说过没有"，不经过本函数。
    """

    out: list[set[str]] = []
    last: set[str] = set()
    for facets in per_turn:
        item = set(facets) if facets else set(last)
        out.append(item)
        if item:
            last = item
    return out


# 换面过渡的候选范例（2026-09-24 去模板化）。
#
# **为什么要改**：旧版只给一个范例，而且每轮都给同一句 ——
#     「手上这件先这样……对了，说起来」
# 60 次云端实测（改后 `7b9aa33`，A/B 两组共 10 轮换面）：「对了，说起来」这一对
# **连用**出现在 5 轮里，形状二的第 3、4、5 轮**连续三轮同款开场**，第 4、5 轮连内容
# 都回环（爆米花同义说两遍）。也就是说：范例被当成了**唯一模板**照抄，
# 换面过渡从改前的"有时硬拐"退化成了"固定一个说法"——把一个问题换成了另一个。
#
# **改法（三条约束都是项目和用户口径的既有约定）**：
#   ① **代码轮换，不靠模型自觉**。不给"别重复用同一个过渡词"这类规则 ——
#      用户口径是「反机械感靠减约束、给示例，不靠加规则」，而"别重复"本身就是
#      又一条可比对的规则。这里改成每轮只注入**一个**范例，由代码换。
#   ② **优先避开最近两轮已经用过的那个**（`_transition_example` 的第一支），
#      真避不开时才按 `anchor` 的稳定哈希兜底。兜底**不用 `len(replies)`**：真机
#      `BridgeClient.MaxHistoryItems = 6`，history 被夹住后长度不再增长、轮换会卡死
#      （正是本次要修的形态）。也不用 `hash()`：PYTHONHASHSEED 跨进程随机化，
#      本项目在群聊记忆 id 上踩过这个坑。
#   ③ **四个候选都不点名任何面**，与下方 `suggestedFacet` / `suggestedTopic` 的
#      单一层级不变：范例只示范"怎么拐"，"拐到哪一面"仍只由槽位唯一给出。
#      四个也都在同一层级（"先收住上一句、再用一个转折词拐出去"），不构成第二层。
_TRANSITION_EXAMPLES: tuple[tuple[str, str], ...] = (
    ("对了", "「手上这件先这样……对了，」"),
    ("说起来", "「……说起来，」"),
    ("还有", "「哦，还有——」"),
    ("话说回来", "「话说回来，」"),
)


def _transition_example(anchor: str, replies: object = ()) -> str:
    """挑一个过渡范例：先排除最近两轮用过的，再在剩下的里按内容稳定哈希挑。

    两层都是必要的：
      · **排除用过的**挡住"模型照抄范例、于是每轮都是同一句"（本次实测的形态）；
      · **池内不总取第一个**挡住另一头——只用排除法时，池子恒以第一个候选开头，
        模型不照抄的那几轮会反复拿到同一个（离线模拟里第 4、5 轮就撞了）。
    哈希用 `zlib.crc32` 而不是内置 `hash()`：后者受 PYTHONHASHSEED 影响、跨进程不稳
    （本项目在群聊记忆 id 上踩过这个坑）。
    """

    texts = [item.strip() for item in (replies or ()) if isinstance(item, str)]
    # 窗口取**最近两条 NPC 回复**（不是按字符数）：要挡的是"相邻两轮同款"，
    # 而上一轮回复里就带着她刚用过的那个过渡词。
    recent = " ".join(texts[-2:])
    pool = [item for item in _TRANSITION_EXAMPLES if item[0] not in recent]
    if not pool:
        pool = list(_TRANSITION_EXAMPLES)
    if len(pool) == 1:
        return pool[0][1]
    material = anchor + "|" + (texts[-1] if texts else "")
    return pool[zlib.crc32(material.encode("utf-8")) % len(pool)][1]


# 「这条素材最近两轮已经被她说出来了」的判据（2026-09-24，方案 4）。
#
# **动机**：`_pick` 原先的去重依据是**判面**（`used`），而模型说的那句话**未必判得出面** ——
# 云端实测（A2 形状）第 4、5 轮她连说了两遍爆米花，而
# `_facet_hits("…加了桦树糖浆的爆米花…")` = **空**（素材条目「加了桦树糖浆的爆米花**食谱**」
# 靠"食谱"两个字才判出「吃喝」）。于是代码认为"吃喝这一面没用过"，第 5 轮把**同一条素材**
# 又推荐了一遍 —— 这就是那次内容回环的直接原因。
#
# **判据**：素材条目与最近两轮回复的 **2-gram 覆盖率** ≥ 阈值即视为"说过了"。
#
# ⚠ **阈值是 13 个实测样本上的观察值，不是统计结论**（样本见
# `.tmp/dq-verify/out/plan4-eval.txt`，脚本 `eval_plan4.py`）：
#   · **整条子串匹配不可用** —— 13 个样本只命中 1 次（素材是描述性短语，
#     模型永远不会说"食谱"那两个字）；
#   · **LCS ≥ 0.5 会漏** ——「酒窖里这一批新酿」vs 她实际说的「那批新酿」= 0.38；
#   · **2-gram ≥ 0.5 在样本上最好** —— 爆米花 0.82/0.64、新酿 0.71、Birdie 芋泥 0.62，
#     而"明显没用素材"的几轮全部 **0.00**（误杀风险低）。
# **它抓不住"换个说法说同一件事"** —— 那种重复更隐蔽、也更像真人在换着说，**刻意不治**。
# 将来样本变多再调这个数。
_TOPIC_ECHO_BIGRAM_RATIO = 0.5


def _topic_already_spoken(
    topic: str,
    replies: list[str],
    *,
    window: int | None = 2,
) -> bool:
    """这条素材是不是**窗口内**已经被她说出来过（方案 4 的去重依据）。

    ``window`` 默认 **2**（＝"最近两轮"）—— 这是 2026-09-24 定阈值时的原口径，
    一个字不改。传 ``None`` 表示**用整段传入文本**：跨轮次状态要的正是这个。
    真机 history 被封顶在 6 条（`BridgeClient.MaxHistoryItems`，约 3 轮），
    "这条素材整场聊过没有"这件事在 history 里问不出来，只能由调用方多带一份
    更长的原文（请求体的 `recentReplies`），再用 ``window=None`` 问它。

    窗口拉长的安全性有实测支撑（`.tmp/topic-probe/crosswindow-diagnose.py`，
    三批真机产物）：24 轮窗口下 2-gram ≥ 0.5 的**假阳只有 0~1 条**，
    而"素材关键词"参照在同段文本上判出 8~9 条 ⇒ 判据偏保守（漏报多、误判几乎没有）。
    """

    if window is None:
        selected = list(replies)
    else:
        selected = list(replies[-window:]) if window > 0 else []
    recent = " ".join(selected)
    if not recent:
        return False
    grams = [topic[index : index + 2] for index in range(len(topic) - 1)]
    if not grams:
        return False
    hits = sum(1 for gram in grams if gram in recent)
    return hits / len(grams) >= _TOPIC_ECHO_BIGRAM_RATIO


# =============================================================================
# 话题深度槽位（2026-09-24）
# =============================================================================
#
# 用户口径是**两件事**：「话题不断有新东西」**和**「同一个话题能聊出不同的感觉」。
# 后者是**纵向**的 —— 同一个话题的不同切面（事实 → 感官 → 回忆 → 情绪 → 矛盾）。
# 在它之前，仓库里只记了前一件，`rotation_topic_slot` 也只做横向（同一个生活面
# 重复 → 禁掉它、换到别的面），**纵向一条机制都没有**。
#
# 实测（走 `app._build_context`，游戏同一条路）：
#
#   · `intent=topic`（她自说自话）30 轮：**6/29 轮与上一轮相似度 ≥0.5**，
#     第 6 轮 vs 第 5 轮 = **1.00（一字不差）**，「毯子+橡树掉叶+第一场雪」
#     被端出来 6 次（第 2、3、7、8、10、11 轮）。
#   · `intent=chat` 8 轮：无逐字重复，但**每轮端出 2~3 件新事**，
#     一个话题碰一下就跳；第 6 轮起出现元对话（「我刚才说得太多了吗？」）
#     与讨好式罗列（「香橙鸡和萤石都得再排排队了」）。
#
# 为什么现有判重拦不住第一件：`_topic_already_spoken` 筛的是**「该建议哪条素材」**
# （见 `rotation_topic_slot` 里的 `spoken` 集合）——它保证建议永远指向一条没说过的话题。
# **可模型根本不看建议，它看 history**，而 history 里全是她自己上一轮说过的话，
# 于是模型顺着自己的回声续写。`intent=topic` 的请求**不写玩家项**，history 6 条
# 全是她自己 ⇒ 回声比 `chat` 路径强得多，这正好解释了为什么逐字重复只在 topic 路径出现。
#
# 加一张卡后的实测：`topic` 路径相邻重复 **6/29 → 0/29**（10 批内最高 0.08），
# `chat` 路径第 6 轮出现「**刚才我说的是毯子的事，但其实……我真正想说的是，
# 能和你一起待着就很好**」、第 8 轮「一个人待着、说不清是舒服还是闷的感觉」。
# 完整设计与实验数据见 `docs/design-topic-depth-2026-09-24.md`。

#: 两个触发名。**互斥且有序**：先看"她是不是在重复自己"（那比"没聊深"更刺眼）。
_DEPTH_TRIGGER_SELF_REPEAT = "selfRepeat"
_DEPTH_TRIGGER_PLAYER_CONTINUATION = "playerContinuation"

#: 判"她自己重复了自己"时往回看几条回复。跨窗口那一份按这个倍数放宽 ——
#: 4 倍 = 24 条，与 `recentReplies` 的上限一致。
_DEPTH_LOOKBACK = 6

#: 判"两段回复是同一件事"的覆盖率门槛。
#:
#: ⚠ **刻意不复用 `_TOPIC_ECHO_BIGRAM_RATIO`（0.5）**：那个数是给
#: "**素材** vs 回复"定的（素材是短的描述性短语，模型不会逐字复述，所以门槛要低）。
#: 这里是"**回复 vs 回复**"，两边体裁相同、用词高度重叠，0.5 会大量假阳 ——
#: 实测 `prod3-chat` 里她每轮内容其实都不同（香橙鸡 / 动漫展 / 炖菜 / 酒窖 /
#: 月光石 / 林中晶体），却因为惯用「我刚才把…」开场而**每轮都判成重复**。
#: 实测真正逐字重复的那几对（Jaccard 口径）是 **0.81~1.00**，换成更敏感的覆盖率
#: 只会更高，所以 0.7 有充足余量、又不会把"句式像"当成"内容重复"。
_DEPTH_REPEAT_RATIO = 0.7

#: 玩家在催她继续、但**没给新话题**。
#:
#: ⚠ 刻意**不复用** `_is_short_filler_reply`：那个要求"整句由空转词拼成"
#: （`_PLAYER_FILLER_FULL_PATTERN`），而「然后呢」「还有呢」带实义虚词、判不出来
#: —— 实测三组里 `playerShortReply` **一次都没触发**（槽位输出全是 `trig=—`）。
#: 这里要的是"玩家在催她继续说"，是另一件事，所以另立一个判据；
#: 也**不去动** `_is_short_filler_reply` 的语义（它管的是"玩家没接住"）。
#:
#: 允许尾部标点与空白（「嗯……」「然后呢？」都算），但**整句必须只有这些** ——
#: 「嗯，你说得对」带实义判断，不算，玩家自己就有话说，不该把她按在旧话题上。
_PLAYER_CONTINUATION_PATTERN = re.compile(
    r"^(?:"
    r"然后呢|后来呢|还有呢|接着说|继续说|说下去|多说点|继续|"
    r"嗯+|哦+|啊+|呃+|唔+|欸+|"
    r"真的|真的吗|是吗|是这样啊|这样啊|原来如此|好吧"
    r")[。！？…，,、\s]*$"
)

def _player_continuation_instruction(quote: str) -> str:
    """把「接着讲」落成**具体**指认 —— 与 `_self_repeat_instruction` 对称。

    **为什么要引用原文**（2026-09-24 晚，设计文档 §十）：触发 A 靠指认引文
    把逐字重复从 6 处压到 0，而触发 B 此前**只有抽象措辞**
    （「就是你们刚才在说的那件」）—— 「那件」是什么全靠模型自己猜，
    它每轮重新猜一次，就端出一件新东西。

    §九 的 3+3 批对照证明深度卡**有效**（对照组三批零纵深、实验组三批有），
    但 §十 证明它**压不死**：禁用横向槽位后她仍在第 3、4 轮换话题
    （香橙鸡、精灵石、海边石头），两批都一样 ⇒ 缺的正是这一层指认。

    引文缺席时不留空引号（那比不引用更糟），其余约束照旧。
    """

    where = f"，就是「{quote}」那段。" if quote else "。"
    return (
        f"本轮只谈一件事，就是你们刚才在说的那件{where}"
        "不要再端出新的东西，也不要用「对了」「而且」「话说回来」另起话头。"
        "把它说完：它具体是什么样子、它让你想到什么、你当时是什么感觉。"
        "说不到三句就停。"
    )

#: 指认"你到底重说了哪一条"时，引用它开头的多少个字。
_DEPTH_QUOTE_CHARS = 18


def _quotable(text: str, limit: int = _DEPTH_QUOTE_CHARS) -> str:
    """截一段话的开头用于**指认**，保留原文标点（只压掉换行与多余空白）。

    与 `_reply_digest` 不同：那个要剥掉标点做 2-gram，这个是要**给人看**的
    ——「你刚才说的是这条」必须一眼认得出，去过标点反而难读。
    """

    flat = " ".join(str(text or "").split())
    if len(flat) <= limit:
        return flat
    return flat[:limit] + "……"


def _self_repeat_instruction(quote: str) -> str:
    """把"别再原样说一遍"落成**具体**指认。

    **为什么要引用原文**（2026-09-24 实测）：抽象禁令无效。
    `prod3-topic` / `prod4-topic` 两批共 54 轮里，`selfRepeat` **几乎每轮都触发**、
    独立卡也每轮都发到了，可逐字重复依然密集（[7]=[6]、[9]=[6]、[11]=[8]、
    [14]=[12]、[22]≈[21]、[23]=[22]、[24]=[21]）。
    原因不是指令被无视，而是**它没有"没提过的"可挑** ——
    `topic` 路径下模型看不到任何玩家输入，可见历史只有 6 条、全是她自己，
    抽象地说"别重复"等于让它在一片回声里自己找出口。
    指认到具体哪一条，才是它能执行的动作。
    """

    where = f"——就是「{quote}」那段" if quote else ""
    return (
        f"你刚才说的那件事{where}，前面已经讲过了。"
        "别再原样说一遍，也别换个说法把同一件重讲一遍。"
        "换一件具体的小事：手边正在做的、刚看到的、或者最近真遇到过的。"
    )


def _bigram_coverage(left: str, right: str) -> float:
    """两段话的 2-gram 覆盖率：**分母取较短的那一方**。

    与 `_topic_already_spoken` 同源口径（那里分母是素材的 gram 数，因为素材短）。
    这里两边都是回复、长度可比，仍取较短者为分母 —— 这样"**重说前半句再继续**"
    也能被抓到（那种情况下长的包含短的，Jaccard 会被长的那段冲稀到 0.5 以下，
    覆盖率则是 1.0）。实测的重复对在 Jaccard 口径下是 0.81~1.00，
    换成更敏感的这个口径只会更高，0.5 的余量足够。

    只算汉字与字母数字（复用 `_reply_digest`），标点与语气词不参与。
    """

    a, b = _reply_digest(left), _reply_digest(right)
    if len(a) < 2 or len(b) < 2:
        return 0.0
    short, long = (a, b) if len(a) <= len(b) else (b, a)
    grams = [short[index : index + 2] for index in range(len(short) - 1)]
    if not grams:
        return 0.0
    hits = sum(1 for gram in grams if gram in long)
    return hits / len(grams)


def _is_player_continuation(text: str) -> bool:
    """玩家在催她继续说，而不是自己带了新话题。"""

    return bool(_PLAYER_CONTINUATION_PATTERN.match(text.strip()))


def topic_depth_slot(
    recent_replies: object = (),
    *,
    player_replies: object = (),
    spoken_replies: object = (),
) -> dict[str, str]:
    """本轮该不该让她"就着同一件事往下走"。返回空字典表示不需要。

    产出形如 ``{"depthTrigger": ..., "instruction": ...}``，与
    `rotation_topic_slot` 的 ``{"trigger": ..., "instruction": ...}`` 并列，
    由调用方渲染成**独立卡** `topic_depth_card` —— **不新增第二套可比对象**
    （本项目记过三次的教训），但**也不能并进 `stage_execution_card`**：
    实测那样会被无视，见下面 `spoken_replies` 的说明与设计文档 §五之二。

    两个触发：

    * ``selfRepeat``：她最近一条回复与更早的某条 2-gram 覆盖率
      ≥ `_TOPIC_ECHO_BIGRAM_RATIO`。措辞**给两条出路**而不是只禁止
      —— 实验与实测都显示她的"重复"与"跳"**同源**：都是急着给东西。
      只堵不疏会让她卡住，这也符合项目铁律（反机械感靠减约束、给示例，不靠加规则）。
    * ``playerContinuation``：玩家本轮只给了"继续说"的信号、自己没带新话题。

    ``spoken_replies`` 是**跨窗口**的那一份（请求体的 `recentReplies`，≤24 条）。
    为什么必须要它：真机 history 被 `BridgeClient.MaxHistoryItems` 封顶在 6 条，
    也就是**约 3 轮**，隔了三四轮的重复在窗口里根本看不见 ——
    实测 `prod2-topic` 第 15 轮重复了第 12 轮，而那时第 12 轮早已滑出窗口，
    槽位全程没触发。这与 ㉗ 给 `rotation_topic_slot` 加这一份是**同一个理由**。

    ⚠ 本槽位有**固有的一轮延迟**：它在"本轮生成之前"算，所以只能发现
    "上一轮重复了更早的"，抓不到"本轮即将重复"。这是时序决定的，不是缺陷；
    实测里一轮之后能拦住。

    **玩家在划边界时不触发** —— 那是 `boundaryMode` 的地盘；
    **玩家自己点名换话题时也不触发** —— 方向盘在玩家手里。
    """

    replies = [
        _player_reply_text(item)
        for item in (recent_replies or ())
        if _player_reply_text(item)
    ]
    players = [
        _player_reply_text(item)
        for item in (player_replies or ())
        if _player_reply_text(item)
    ]

    # 玩家划边界 or 明确点名换话题 —— 本轮一律不压她。
    if players:
        latest_player = players[-1]
        if _is_player_refusal(latest_player) or _is_player_topic_request(latest_player):
            return {}

    if not replies:
        return {}

    # 触发 B **先判**：玩家在催她继续说（自己没带新话题）时，他要的是"接着讲"，
    # 不是"换一件"。
    #
    # ⚠ **顺序在 2026-09-24 的实测里反过来过一次，结果很明显**：那时 A 在前，
    # 于是玩家每轮只说「嗯」「然后呢」的整段对话里，她收到的一直是 A 的文案
    # ——「要么换一件确实没提过的，要么就着它往下走一层」。**她选了更容易的那条**，
    # 每轮端出一件新事（香橙鸡→动漫展→炖菜→酒窖→月光石→林中晶体），
    # 正是用户抱怨的"聊不出不同的感觉"。两个触发同时成立时，**玩家的意图优先**。
    if players and _is_player_continuation(players[-1]):
        return {
            "depthTrigger": _DEPTH_TRIGGER_PLAYER_CONTINUATION,
            "instruction": _player_continuation_instruction(_quotable(replies[-1])),
        }

    # 触发 A：她最近这条与更早的某条高度重合。
    #
    # "最近这条"只能来自 `recent_replies`（它是本轮之前最近的几条）；
    # 而"更早的"要把跨窗口那一段也算进来 —— 见 docstring 里 `prod2-topic` 那次。
    # 两者接起来时**跨窗口在前**，保持时间顺序（它是更早的原文）。
    earlier = [
        _player_reply_text(item)
        for item in (spoken_replies or ())
        if _player_reply_text(item)
    ] + replies[:-1]
    latest = replies[-1]
    repeat_of, best_score = "", 0.0
    for candidate in earlier[-_DEPTH_LOOKBACK * 4 :]:
        score = _bigram_coverage(latest, candidate)
        if score > best_score:
            repeat_of, best_score = candidate, score
    if best_score >= _DEPTH_REPEAT_RATIO:
        return {
            "depthTrigger": _DEPTH_TRIGGER_SELF_REPEAT,
            "instruction": _self_repeat_instruction(_quotable(repeat_of)),
        }

    return {}


def rotation_topic_slot(
    preferred_topics: object = None,
    *,
    recent_replies: object = (),
    player_replies: object = (),
    turn_players: object = (),
    spoken_replies: object = (),
) -> dict[str, Any]:
    """按最近轮次算一个「本轮换面」的硬槽位；不需要换时返回空 dict。

    ``recent_replies`` 是**时间正序**的 NPC 回复文本（调用方从 history 里取 assistant 项）。
    ``player_replies`` 是同一份 history 里**玩家的**回复文本，同样时间正序，**末尾是
    本轮玩家的话**（游戏端本轮不在 history 里，调用方必须自己并上去）；调用方
    省略时行为与 2026-09-21 版完全一致（只有"同面重复"这一个触发条件）。
    ``turn_players`` 是**与 ``recent_replies`` 逐项对齐**的玩家提问（同长度、同时间正序），
    用于轮次共指：她那一轮用的是指代（"那幅画／刚封好的那批"）时，对象在玩家的话里。

    三个触发理由，**最多两个同时成立**（`playerShortReply` 与 `playerAsksNewTopic`
    互斥：「换个话题」这几个字切不出空转词，不是敷衍）：

    * ``facetRepeat``：最近 ``_FACET_LOOKBACK`` 轮里同一个生活面出现
      ``_FACET_REPEAT_THRESHOLD`` 次。这是"**她**说腻了"。
    * ``playerShortReply``：玩家**本轮**回复很短且是敷衍类。这是"**玩家**没接住"，
      也是"主动权在 NPC 手里"的信号源 —— 不用玩家去点"找话题"。
    * ``playerAsksNewTopic``：玩家**本轮**明确要求换个话题。

    `bannedFacet`（"本轮要换掉的那一面"）与 `trigger` **不再等价**（2026-09-23）：
    前者有三级证据来源（见函数内的 `banned_source`），后者只报**触发理由**。

    两条**不产出槽位**的路径（都写在常量区的防误判里）：玩家在划边界
    （``_PLAYER_REFUSAL_MARKERS``，交给 `boundaryMode` 收口）；玩家本轮自己
    把话带回了被禁的那个面 —— 见下面对"撤回"的说明。

    ``spoken_replies``（2026-09-23）是**跨窗口**的那一份原文：与 ``recent_replies``
    同样的文本、但来自请求体的 `recentReplies`（Mod 端从回看档案取），比发送窗口长。
    它**只**参与"这条素材谈过没有"的判定，**不**参与 ``facetRepeat`` 的计数 ——
    后者那 3 轮窗口是「主动权在她，方向盘在你手里」这条用户口径调出来的，一个字不动。
    """

    replies = [
        item.strip()
        for item in (recent_replies if isinstance(recent_replies, (list, tuple)) else ())
        if isinstance(item, str) and item.strip()
    ][-_FACET_LOOKBACK:]
    # 跨窗口那一份（2026-09-23）：**不截断**（调用方已按上限给量），
    # 只在这里去空白。理由见 `spoken_replies` 的说明与 `_topic_already_spoken`。
    cross_replies = [
        item.strip()
        for item in (spoken_replies if isinstance(spoken_replies, (list, tuple)) else ())
        if isinstance(item, str) and item.strip()
    ]
    player_texts = [
        text
        for text in (
            _player_reply_text(item)
            for item in (player_replies if isinstance(player_replies, (list, tuple)) else ())
        )
        if text
    ]
    # 只认**最近一条**玩家回复：上一轮敷衍、这一轮认真说了话，不该再补一次换面。
    player_text = player_texts[-1] if player_texts else ""

    # ① 玩家在划边界：**整轮不产出槽位**。玩家正在划线，NPC 却像没听见一样换台，
    #    读起来既不尊重也不像本人；边界该由 `boundaryMode` 收口。
    if player_text and _is_player_refusal(player_text):
        return {}

    # 判不出面的轮次按"继承上一轮的面"折算（2026-09-22），理由见 `_fold_missing_facets`：
    # 实测 5/5 的「无面」都是词表没收录的同义说法，丢弃它们等于把她的持续话题当没发生。
    per_reply = _fold_missing_facets(_facet_per_turn(replies, turn_players))
    # **计数**而不是取交集：一句话常同时命中"工作"与"天气"，取交集要求两轮都命中
    # 同一面，隔一轮的形状直接漏掉（见 `_FACET_LOOKBACK` 的注释）。
    counts: dict[str, int] = {}
    for facets in per_reply:
        for facet in facets:
            counts[facet] = counts.get(facet, 0) + 1
    repeated = {
        facet for facet, count in counts.items() if count >= _FACET_REPEAT_THRESHOLD
    }

    short_reply = bool(player_text) and _is_short_filler_reply(player_text)
    asks_new_topic = bool(player_text) and _is_player_topic_request(player_text)
    if not repeated and not short_reply and not asks_new_topic:
        return {}

    # 多个面同时重复时（一句话常同时命中"工作"与"天气"）只压一个：优先压
    # **该角色素材里占比最高**的那一面，因为那正是模型被反复牵回去的地方。
    topics = [
        item.strip()
        for item in (preferred_topics if isinstance(preferred_topics, (list, tuple)) else ())
        if isinstance(item, str) and item.strip()
    ]
    topic_facets = [_facet_of_topic(item) for item in topics]
    # tie-break 用**声明顺序**而不是 `facet` 字符串：字符串比较在这里只是"随便挑
    # 一个确定的"，而声明顺序是把「工作或手艺」排在第一位的那份优先级表 ——
    # 语义上"素材占比相同时，先压更靠前的那一面"。
    facet_order = {name: index for index, (name, _) in enumerate(_LIFE_FACET_PATTERNS)}

    def _strongest(candidates: set[str]) -> str:
        """候选面里挑**本轮要压的那一个**：先比素材占比，再比声明顺序。

        下面三级证据（重复面／她最近一面／她惯常的落点）共用这一个选择器 —— 它们是
        **同一个字段**（`bannedFacet`）的三个证据来源，不是三个可比对象。
        """

        return max(
            candidates,
            key=lambda facet: (topic_facets.count(facet), -facet_order.get(facet, 0)),
        )

    # 建议去哪个面：优先该角色**自己素材里就有**、最近没用过、且不与禁令同面的那一条。
    #
    # 降级（2026-09-21 二次）：候选为空时不再直接放弃，而是退一步 —— 允许回到最近几轮
    # 用过、但**没有被禁**的面。用户点名的"隔一轮提同一件事"形状下，素材只覆盖两个面
    # 的角色（索菲亚＝工作／镇上）会让 `used` 立刻等于它的全部素材面，旧写法于是**每一
    # 轮**都落进"没有候选"的泛化分支，建议指向它根本没有素材的面（吃喝、天气、家人…）
    # ——"换到空的"比不换更差。禁令只针对 `banned` 这一面，回到别的面并不违规。
    #
    # 2026-09-23：本块**上移**到 `banned` 之前。下面的「她惯常的落点」那一级要用它 ——
    # 那正是它在"无禁令、不拿 `used` 筛"时会返回的那一条。复制一份等价逻辑会让
    # "默认落点"有两份定义（本项目记过的形状），所以宁可在同一个函数里把顺序调过来。
    used = set().union(*per_reply) if per_reply else set()
    # 方案 4（2026-09-24）：判面之外再加一层"**这条素材本身**最近两轮说过没有"。
    # 判据与阈值理由见 `_TOPIC_ECHO_BIGRAM_RATIO` 上方注释。
    #
    # 2026-09-23（跨轮次状态）：再加一层**跨窗口**的同一判据。上面那层的窗口是
    # history 给的 3 轮，第 4 轮起早期素材被挤出去、重新变回"没谈过"，于是池子前
    # 几条被反复建议。跨窗口那一份（`spoken_replies`）比窗口长，判据同源
    # （`window=None` 用整段），因此"整场谈过没有"这件事第一次问得出来。
    # 判据本身偏保守（假阳 0~1 条，见 `_topic_already_spoken`），排除不足但不会误杀。
    spoken = {
        topic
        for topic in topics
        if _topic_already_spoken(topic, replies)
        or (
            cross_replies
            and _topic_already_spoken(topic, cross_replies, window=None)
        )
    }

    # 候选的**遍历起点**不总在池子头部（2026-09-25）。
    #
    # 只用"排除说过的（`spoken`）＋ 排除用过的面（`used`）"是不够的：这两个窗口
    # **都来自 history**，而真机的 history 被封顶在 6 条 ＝ 3 轮
    # （`BridgeClient.MaxHistoryItems`）⇒ 第 4 轮起早期素材就被挤出窗口、
    # 重新变成"没谈过"。此时从头部遍历会让**池子前 N 条被反复选中，后面的永远轮不到**，
    # 而 N 只由窗口大小决定，**与池子多大无关** —— 所以"补素材"单独解决不了"聊不长"。
    #
    # 离线模拟（24 轮、12 条池、假设她逐字复述被建议的素材，即对机制最有利）：
    #   · 从头部遍历：只覆盖 **4/12** 条，四条各出现 6 次，呈严格 4 周期；
    #   · 起点按内容哈希偏移：覆盖 **9/12** 条，最高频次降到 4。
    #
    # 这与 `_transition_example` 记的是**同一个形状**（那里写的是"只用排除法时，
    # 池子恒以第一个候选开头"），所以同样用 `zlib.crc32` —— 内置 `hash()` 受
    # PYTHONHASHSEED 影响、跨进程不稳（本项目在群聊记忆 id 上踩过）。
    #
    # `rotated=False` 专供"她惯常的落点"那一级：那一级的定义就是**不加任何筛选时
    # `_pick` 会返回的那一条**，必须与轮次无关，否则禁令的来源会逐轮漂移。
    scan = topics
    if topics:
        material = "\x1f".join(replies[-4:]) if replies else ""
        offset = zlib.crc32(material.encode("utf-8")) % len(topics)
        scan = topics[offset:] + topics[:offset]

    def _pick(
        allow_used: bool, *, skip_spoken: bool = True, rotated: bool = True
    ) -> tuple[str, str]:
        for topic in (scan if rotated else topics):
            facet = _facet_of_topic(topic)
            if not facet or facet == banned:
                continue
            if skip_spoken and topic in spoken:
                continue
            if not allow_used and facet in used:
                continue
            return topic, facet
        return "", ""

    # 本轮**要换掉的那一面**（`bannedFacet`）。三级证据、逐级降级（`banned_source`）：
    #   · `repeat`：重复面（`facetRepeat`，现状）；
    #   · `latest`：她最近一轮的面（`playerAsksNewTopic` 单独触发时，N=1）；
    #   · `default`：她惯常的落点（连 `latest` 都拿不到时）。
    # 三级产出的都是**同一个字段**，措辞层也只有一个禁令句 —— 不新增第二个可比对象。
    # 编号刻意不用 ①②③：本函数前半段已经用它标了"玩家划边界"与"撤回"两个分支。
    banned = _strongest(repeated) if repeated else ""
    banned_source = "repeat" if banned else ""

    # `playerAsksNewTopic` **单独**触发时补上参照物（2026-09-23）。
    #
    # 玩家明确说「换个话题」时，代码得知道"换掉哪一面"才谈得上换。在此之前
    # `bannedFacet` **只由 `facetRepeat` 提供**，于是没有重复面的轮次里它是空的，
    # instruction 落进"随便挑一面"那条分支 —— 而"随便挑"并不随机：`_pick` 在无禁令、
    # `used` 为空时确定性地返回**素材第一条**，也就是这个角色的职业主面。
    # 真机 S13（玩家开口第一句就是「换个话题吧」）渲染出来的是：
    #     「…本轮由你主动把话头换一次，不要再绕着刚才那一面打转。改从「工作或手艺」
    #       这一面挑一件…（例如「酒窖里这一批新酿」这个方向）…」
    # —— 玩家要换话题，她照着这句去聊酒；而"刚才那一面"在零历史下**无所指**。
    #
    # 两级降级：
    #   · `latest`：有历史但没有重复 ⇒ 用**最近一轮她自己的面**。玩家说的"换个话题"
    #     指的就是他刚看到的最后那一轮，所以这一级与 `anchor`（同样取 `replies[-1]`）
    #     **同轮同源**，不会出现"接住这一轮、却换掉另一轮"的错位。
    #   · `default`：最近一轮判不出面、或一句历史都没有 ⇒ 用**她惯常的落点**（`_pick`
    #     不加任何筛选时会返回的那一条）。这一级不声称"她刚才在聊"，只声明"别又起在
    #     这一面"。
    #     "干脆让她自由挑"在这里**不成立**：自由挑的实现就是回到素材第一条，而
    #     `narrow_topic_pool` 也会因为没有禁令、把这一面的素材照旧留在落点池里 ——
    #     S13 那个"要她换话题、她偏聊酒"正是这两层一起造成的。
    if not banned and asks_new_topic:
        latest = per_reply[-1] if per_reply else set()
        if latest:
            banned = _strongest(latest)
            banned_source = "latest"
        else:
            # 「她惯常的落点」＝素材里第一条**判得出面**的条目，也就是**不加任何筛选**
            # 时 `_pick` 会返回的那一条（这里 `allow_used=True` 读作"别拿 `used` 筛"）。
            #
            # **不能**用 `allow_used=False`：那一支挑的是"最近**没**用过"的面，于是有
            # 历史时这一级给出的禁令由 `used` 决定，不再是"她惯常的落点"。具体代价：
            # S3 前两轮（R1 工作面、R2 是纯指代判不出面）下它会禁掉**镇上**、把她推回
            # 工作面 —— 而她最近聊的正是工作面，与"换个话题"正好相反。
            # `skip_spoken=False`：这一级要的正是"**不加任何筛选**时 `_pick` 会返回的
            # 那一条"，方案 4 的"说过没有"筛选同样不能参与（见 `_TOPIC_ECHO_BIGRAM_RATIO`）。
            # `rotated=False`（2026-09-25）：遍历起点同样不能参与 —— 上面 `scan` 那个
            # 偏移是给"本轮建议去哪条"用的，它逐轮变化；而这一级声明的是**她惯常的
            # 落点**，逐轮漂移的"惯常"不成立，且会让 `default` 这一级的禁令来源不稳定。
            _, default_facet = _pick(allow_used=True, skip_spoken=False, rotated=False)
            if default_facet:
                banned = default_facet
                banned_source = "default"

    # ② **撤回**：玩家本轮自己把话带回了被禁的那个面 —— 整轮不产出槽位。
    #
    # 这是用户点名要保住的那条（"主动权在她，但方向盘在你手里"）的**代码落点**：
    # 她刚主动换出去，玩家说「那批新酿到底怎么样了？」，此时若照旧换面，就是
    # "她想聊什么就聊什么"；撤回之后禁令与收窄一起失效，`roleGuidance` 的落点池
    # 里酒的素材**还在**，她回来时有东西可落。
    #
    # 为什么不是"接住但不许延伸"：那只改了措辞，`narrow_topic_pool` 仍然把这一面
    # 的素材从她的池子里抽走 —— 接住了也接不下去。
    #
    # 判据复用 `_LIFE_FACET_PATTERNS`（不另建词表）：玩家这条话**落在被禁的那个
    # 生活面上**就算。只聊别的面不算，否则"玩家说了任何实质内容"都会取消换面。
    #
    # 2026-09-23：判定对象跟着 `bannedFacet` 一起变宽（`latest` / `default` 两级的
    # 禁令也参与撤回）。语义没变，反而更完整：玩家本轮把话带回了"这一轮本来要换掉的
    # 那一面" ⇒ 那就不换。
    if banned and player_text and banned in _facet_hits(player_text):
        return {}

    suggested_topic, suggested_facet = _pick(allow_used=False)
    if not suggested_topic:
        suggested_topic, suggested_facet = _pick(allow_used=True)
    if not suggested_topic:
        # 第三级降级（2026-09-24 方案 4 加）：连"最近没用过的面"都挑不出来时，才允许
        # 回到刚说过的那条素材。宁可重复，也不要像旧写法那样建议一个**这个角色根本
        # 没有素材的面**（"换到空的"比不换更差）—— 与上面两级是同一个降级方向，
        # 只是多松一格 `skip_spoken`。
        suggested_topic, suggested_facet = _pick(allow_used=True, skip_spoken=False)

    # 措辞（2026-09-22 重写）。三处按本次口径调整：
    #
    # ① **换面必须带关联过渡**（用户抱怨的"硬拐"）。旧版是一句纯封口：
    #    「本轮不要再出现这一面的对象、动作或说法」——模型照做的方式就是**另起一件
    #    事**，中间没有那条线。新版把上一轮回复的**首句原文**引进来当作起点，
    #    要求"先接住那里面的具体东西，再从它拉一根线过去"。
    #    引用由**代码**摘（`_bridge_anchor`），不让模型自己回忆：compact 路径下模型
    #    只看得见 4 条 history，而槽位算在完整 history 上。
    # ② **玩家点名豁免升级**。旧版后半句「接住之后不要由你往这一面延伸」在"玩家还想
    #    聊原来的"场景里恰恰是拦路的。新版改成"他要是继续追问这一面，就顺着他的
    #    方向聊"——主动权在角色（由她拉线换面），方向盘在玩家（他拉回来她就跟）。
    # ③ **理由句与触发一致**：没有 `facetRepeat` 时不许出现"最近N轮里有M轮在谈"，
    #    否则模型读到的理由与真实触发不符（B 触发时那一面并没有被禁）。
    #    2026-09-23：禁令的来源变成三级（`banned_source`），理由句跟着分三支 ——
    #    三支都必须**点名**那个面，否则下面"别再以**这一面**做新的落点"无所指。
    anchor = _bridge_anchor(replies[-1]) if replies else ""
    player_quote = player_text[:_PLAYER_QUOTE_LIMIT]
    parts: list[str] = []
    if banned_source == "repeat":
        parts.append(
            f"最近{len(replies)}轮里有{counts.get(banned, 0)}轮在谈「{banned}」这一面；"
        )
    elif banned_source == "latest":
        parts.append(f"你最近谈的还是「{banned}」这一面；")
    elif banned_source == "default":
        # 措辞与另外两支**同型**（都是"她落在哪一面"的陈述），因为这一支同时覆盖
        # 两种进入路径：真的零历史、以及有历史但她最近一轮判不出面。"别再往…起头"
        # 放在"玩家明确要你换个话题"**之前**会读成因果倒置。
        parts.append(f"你惯常的落点是「{banned}」这一面；")
    if short_reply:
        parts.append(f"玩家最近只回了「{player_quote}」几个字，没接住你的话头；")
    if asks_new_topic:
        parts.append(f"玩家明确要你换个话题（他刚说：「{player_quote}」）；")
    if anchor:
        parts.append(
            f"上一轮你说过：「{anchor}」。本轮先接住那里面的具体东西，"
            "再从它拉一根线过去、换到别的面，不要凭空跳过去。"
        )
    # 没有 anchor（history 里压根没有她的上一轮，例如玩家开口第一句就是「嗯」）时
    # **不写**过渡句：没有可拉的那根线，"先接住上一轮的…"是一句读不通的指令。
    if banned:
        # 原先这里后半句是括号里的"（玩家本轮自己点名的对象仍要接住；他要是继续追问
        # 这一面，就顺着他的方向聊，别为了换面绕开它）"——2026-09-22 已升成独立字段
        # `playerAnchor`（理由见 `_PLAYER_ANCHOR_CONSTRAINT`）：留在括号里，它在"本轮
        # 由你主动把话头换一次"这条主线下面读起来就是可选项。
        #
        # 2026-09-23：**禁令改成范例**（用户拍板的方向：「反机械感靠减约束、给示例，
        # 不是靠加规则」）。旧句是
        #     「别再以这一面做新的落点；换物件、换时段或换个说法讲同一件事都不算换。」
        # —— 三个"不算换"是一份**反例清单**：它只说什么是错的，模型得自己反推出
        # 该怎么做，于是照做的方式恰好是"另起一件事"（用户抱怨的"硬拐"）。
        # 新版换成一个**范例**，示范同一件事的正向形状：把上一句收住，再用
        # 「对了」「说起来」这种转折词拐出去。三点考量：
        #   ① **意图一个字没丢**：末句"不要以同一面另起一件事"就是旧句"换物件/换时段/
        #      换个说法都不算换"的正面表述 —— 三个出口堵成一个。
        #   ② **单一层级照旧**：范例只示范"怎么拐"，**不点名任何面**（"换到哪一面"
        #      仍由下面的 `suggestedFacet` / `suggestedTopic` 唯一给出）。范例里若写死
        #      "……对了，镇上今天有人为摊位吵起来了"，在被禁面恰好是"镇上或邻里"的那
        #      一轮就会**示范换到被禁的那一面**，自相矛盾。
        #   ③ **与 anchor 那句同向**：上一句已经教了"从上一轮拉一根线过去"，这里给的是
        #      那根线**长什么样**（一个可照抄的句式），不是第二条规则。
        # instruction 总长仍在 `_compact_stage_policy` 的 300 字以内（最坏组合 237 字），
        # 回归在 `test_topic_bridge_transition.py::test_every_instruction_fits_the_compact_whitelist_limit`。
        #
        # 2026-09-24 **去模板化**：范例从"固定一句"改成**四个候选、按 anchor 确定性轮换**
        # （动机与三条约束见 `_TRANSITION_EXAMPLES` 上方的注释）。同时把末句的
        # 「再用「对了」「说起来」拐到别的面」改成「再用**一个转折词**拐到别的面」——
        # 原句把两个具体的词又写了一遍，等于在一句里强化同一个模板。
        parts.append(
            f"这一面本轮先搁着——像这样换：{_transition_example(anchor, replies)}，"
            "先把上一句收住，再用一个转折词拐到别的面，不要以同一面另起一件事。"
        )
    else:
        # 没有面可禁（B/C 理由）：要的是"换个落点"，不是封口——凭空禁一面会把
        # 玩家正在聊的东西一起压掉。
        # 2026-09-23：零历史（她一句都还没说过）时"刚才那一面"**无所指** —— 玩家开口
        # 第一句就是「嗯」、或第一句就说「换个话题」而该角色连素材都没有，都会落到这里。
        # 换成不指代的说法，否则模型读到的"那一面"是一个没有先行词的指代。
        parts.append(
            "本轮由你主动把话头换一次，不要再绕着刚才那一面打转。"
            if replies
            else "本轮由你起一个新的话头，不要沿用你惯常的那种开场。"
        )
    if suggested_topic:
        # 「建议的面最近刚用过」是**素材缺口**下的常态，不是 bug：索菲亚 4 条素材
        # 只覆盖两个面（工作／镇上），对话到第三轮就穷尽，`_pick` 的第一轮（不许
        # 用过的面）必然选空、退化到第二轮。此时若照旧说"改从这一面挑一件小事"，
        # 模型很可能把**刚才那件事**再说一遍 —— 那是"换了面"字面成立、体感没换。
        # 措辞因此分成两支：面是新的时候说"改从这一面"，面刚用过时说"**另一件**事"。
        if suggested_facet in used:
            parts.append(
                f"改从「{suggested_facet}」这一面挑**另一件**具体的、能落到对白里的"
                f"小事来说（例如「{suggested_topic}」这个方向，但不要重复刚才那件），"
                "只说一件，不要罗列。"
            )
        else:
            parts.append(
                f"改从「{suggested_facet}」这一面挑一件具体的、能落到对白里的小事来说"
                f"（例如「{suggested_topic}」这个方向），只说一件，不要罗列。"
            )
    else:
        parts.append(
            "换到另一个生活面（吃喝、天气季节、镇上或邻里、家人朋友、玩家自己、"
            "自己的状态或烦恼、过去的回忆、爱好或消遣）挑一件具体的、"
            "能落到对白里的小事来说，只说一件，不要罗列。"
        )
    instruction = "".join(parts)

    triggers = [
        name
        for name, active in (
            # 2026-09-23：判据从 `bool(banned)` 改回 `bool(repeated)`。禁令现在也可能由
            # `playerAsksNewTopic` 的降级提供，而 `trigger` 说的是**理由** ——
            # 不能因为禁令在场就报出一个并没有发生的 `facetRepeat`。
            ("facetRepeat", bool(repeated)),
            ("playerShortReply", short_reply),
            ("playerAsksNewTopic", asks_new_topic),
        )
        if active
    ]

    slot: dict[str, Any] = {
        "instruction": instruction,
        "trigger": "+".join(triggers),
        # 「玩家点名的对象要接住」是**无条件**硬约束（2026-09-22 从 instruction 的括号
        # 从句升上来）：不管本轮触发的是"她说腻了"还是"玩家没接住"，玩家自己点名的
        # 东西都要先接住。代码层的撤回（玩家点名被禁面 ⇒ 整轮不产出槽位）只在"点的
        # 正好是被禁那一面"时生效，其余情况全靠这一条。
        "playerAnchor": _PLAYER_ANCHOR_CONSTRAINT,
    }
    if banned:
        slot["bannedFacet"] = banned
    if suggested_topic:
        slot["suggestedFacet"] = suggested_facet
        slot["suggestedTopic"] = suggested_topic
    return slot


