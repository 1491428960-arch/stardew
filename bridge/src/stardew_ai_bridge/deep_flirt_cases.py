def _state(**values: object) -> tuple[tuple[str, object], ...]:
    return tuple((key, value) for key, value in values.items() if value not in (None, ""))


def _turn(
    turn_id: str,
    message: str,
    expected_terms: tuple[str, ...],
    focus: str,
    initiative_expectation: str,
    initiative_kind: str,
    *,
    forbidden_terms: tuple[str, ...] = ("命中注定", "永远属于"),
) -> CharacterQualityTurn:
    return CharacterQualityTurn(
        turn_id=turn_id,
        message=message,
        expected_terms=expected_terms,
        forbidden_terms=forbidden_terms,
        evaluation_focus=focus,
        initiative_expectation=initiative_expectation,
        initiative_kind=initiative_kind,
    )


def _player_card(
    *,
    relationship_stance: str,
    language_texture: str,
    helping_impulse: str,
    distance_pattern: str,
    flirt_progression: str,
    boundary_style: str,
    self_correction: str,
    forbidden_tendencies: tuple[str, ...],
) -> PlayerExpressionCard:
    return PlayerExpressionCard(
        relationship_stance=relationship_stance,
        language_texture=language_texture,
        helping_impulse=helping_impulse,
        distance_pattern=distance_pattern,
        flirt_progression=flirt_progression,
        boundary_style=boundary_style,
        self_correction=self_correction,
        forbidden_tendencies=forbidden_tendencies,
    )


def _case(
    *,
    case_id: str,
    profile_key: str,
    npc_id: str,
    display_name: str,
    source_mods: tuple[str, ...],
    relationship_stage: str,
    friendship_hearts: int,
    relationship_context: str,
    story_progress: str,
    location: str,
    topic_seed: str,
    topic_keywords: tuple[str, ...],
    turns: tuple[CharacterQualityTurn, ...],
    flirt_intensity: str,
    player_expression_card: PlayerExpressionCard,
) -> CharacterQualityCase:
    if len(turns) != 3:
        raise ValueError(f"深入调情案例必须有三轮：{case_id}")
    first_turn = turns[0]
    return CharacterQualityCase(
        case_id=case_id,
        profile_key=profile_key,
        npc_id=npc_id,
        display_name=display_name,
        source_mods=source_mods,
        relationship_stage=relationship_stage,
        channel="face_to_face",
        message=first_turn.message,
        intent="chat",
        topic_seed=topic_seed,
        topic_keywords=topic_keywords,
        friendship_hearts=friendship_hearts,
        flirt_intensity=flirt_intensity,
        player_expression_card=player_expression_card,
        adult_consensual=True,
        romance_eligible=True,
        follow_up_mode="fixed",
        relationship_context=relationship_context,
        expected_terms=first_turn.expected_terms,
        forbidden_terms=first_turn.forbidden_terms,
        game_state=_state(
            relationship=relationship_stage,
            friendshipHearts=friendship_hearts,
            location=location,
        ),
        story_progress=story_progress,
        turns=turns,
    )


